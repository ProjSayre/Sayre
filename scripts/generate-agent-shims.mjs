// Emits .claude/agents/*.md from .sdd/runtimes.yml (PL-03a).
//
// Usage:
//   node scripts/generate-agent-shims.mjs            # writes .claude/agents/*
//   node scripts/generate-agent-shims.mjs --check    # exit 1 + diff if any shim is stale
//   node scripts/generate-agent-shims.mjs --force    # overwrite even a shim with uncommitted changes
//
// Design notes (see .pipeline/spec.md / .sdd/README.md for the full rationale):
// - .claude/ is the only generation target today. Frontmatter (tools, model, hooks, subagent
//   name) is runtime-specific and lives in .sdd/runtimes.yml; the neutral procedure a shim points
//   at lives in .sdd/stages/<stage>.md and is never duplicated into the shim body.
// - A stage entry with a `neutral` path that doesn't exist on disk is a hard failure: this script
//   never emits a shim pointing at a nonexistent file (fails loudly, before writing anything).
// - Regeneration warns and refuses to overwrite a shim that has uncommitted changes in git and
//   would otherwise be clobbered, so a hand-edit made but not yet committed isn't silently lost.
//   `--force` is the documented override (review W5): without it, the dirty-tree refusal also
//   blocks the ordinary edit-runtimes.yml -> regenerate -> edit-again loop, since regeneration's
//   own output leaves the shim "dirty" until it's committed. `--force` never skips the
//   missing-neutral-file failure above — that one is never overridable.
// - Output uses `\n` line endings unconditionally; `.gitattributes` pins LF on these paths so
//   --check is byte-stable across Windows and Linux checkouts.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __filename = fileURLToPath(import.meta.url);
const scriptsDir = dirname(__filename);
const repoRoot = resolve(scriptsDir, '..');
const sddDir = join(repoRoot, '.sdd');
const runtimesPath = join(sddDir, 'runtimes.yml');
const claudeAgentsDir = join(repoRoot, '.claude', 'agents');

// PL-04 / item 2 (the general defect): the only flags this CLI recognizes. Every argv token used to
// be checked independently via `.includes(...)`, so anything else (a typo like `--froce`, or any
// other unrecognized token) was silently ignored rather than rejected — the same "typo'd flag must
// never look like it worked" fix applied throughout scripts/. `fail` is a hoisted function
// declaration (defined further down this file), so it's safe to call here at module top level.
const KNOWN_FLAGS = new Set(['--check', '--force']);
const cliArgs = process.argv.slice(2);
for (const arg of cliArgs) {
  if (!KNOWN_FLAGS.has(arg)) {
    fail(`unrecognized argument "${arg}" — known flags: --check, --force. A typo'd flag must never look like it worked.`);
  }
}
const checkMode = cliArgs.includes('--check');
const forceMode = cliArgs.includes('--force');

function readText(path) {
  return readFileSync(path, 'utf8');
}

function loadRuntimes() {
  if (!existsSync(runtimesPath)) {
    fail(`Cannot generate shims: ${relFromRoot(runtimesPath)} does not exist.`);
  }
  const parsed = yaml.load(readText(runtimesPath));
  if (!parsed || typeof parsed !== 'object' || !parsed.stages) {
    fail(`${relFromRoot(runtimesPath)} is missing a top-level "stages" map.`);
  }
  return parsed;
}

function relFromRoot(path) {
  return path.split(repoRoot + '\\').join('').split(repoRoot + '/').join('').replace(/^[\\/]/, '');
}

function fail(message) {
  process.stderr.write(`generate-agent-shims: ${message}\n`);
  process.exit(1);
}

/** Build the frontmatter + pointer body for one stage's Claude shim, matching the hand-authored
 * shims this replaces byte-for-byte apart from intentional drift corrections (see changes.md). */
function buildShimContent(stageKey, stage) {
  const claude = stage.claude;
  const lines = ['---'];
  lines.push(`name: ${claude.name}`);
  lines.push(`description: ${claude.description.trim()}`);
  lines.push(`tools: ${(claude.tools ?? []).join(', ')}`);
  if (claude.disallowedTools?.length) {
    lines.push(`disallowedTools: ${claude.disallowedTools.join(', ')}`);
  }
  if (claude.hooks) {
    lines.push('hooks:');
    for (const [event, entries] of Object.entries(claude.hooks)) {
      lines.push(`  ${event}:`);
      for (const entry of entries) {
        lines.push(`    - matcher: "${entry.matcher}"`);
        lines.push('      hooks:');
        lines.push('        - type: command');
        lines.push(`          command: "${entry.command}"`);
      }
    }
  }
  lines.push(`model: ${claude.model}`);
  lines.push('---');
  lines.push('');
  lines.push('<!-- GENERATED by scripts/generate-agent-shims.mjs from .sdd/runtimes.yml — do not edit. -->');
  lines.push(`Follow \`.sdd/${stage.neutral}\` exactly. It is the authoritative definition of this stage.`);
  lines.push('');
  return lines.join('\n');
}

function isGitDirty(absPath) {
  const relPath = absPath.split(repoRoot).join('').replace(/^[\\/]/, '').split('\\').join('/');
  try {
    const output = execFileSync('git', ['status', '--porcelain', '--', relPath], {
      cwd: repoRoot,
      encoding: 'utf8'
    });
    return output.trim().length > 0;
  } catch {
    // No git available (or not a repo) — can't determine dirtiness, so don't claim it's clean.
    // Treat as "unknown, be cautious" only in write mode; --check doesn't call this at all.
    return true;
  }
}

function main() {
  const runtimes = loadRuntimes();
  const stageEntries = Object.entries(runtimes.stages);

  // Fail loudly up front if any stage points at a neutral file that doesn't exist — never emit a
  // shim pointing at a nonexistent path.
  const missingNeutral = [];
  for (const [stageKey, stage] of stageEntries) {
    if (!stage.neutral) {
      missingNeutral.push(`${stageKey}: no "neutral" path declared`);
      continue;
    }
    const neutralAbs = join(sddDir, stage.neutral);
    if (!existsSync(neutralAbs)) {
      missingNeutral.push(`${stageKey}: neutral file .sdd/${stage.neutral} does not exist`);
    }
  }
  if (missingNeutral.length) {
    fail(`refusing to generate — missing neutral stage file(s):\n  ${missingNeutral.join('\n  ')}`);
  }

  const targets = [];
  for (const [stageKey, stage] of stageEntries) {
    if (!stage.claude) continue; // no Claude target declared for this stage
    const content = buildShimContent(stageKey, stage);
    const filePath = join(claudeAgentsDir, `${stage.claude.name}.md`);
    targets.push({ stageKey, filePath, content });
  }

  if (checkMode) {
    const stale = [];
    for (const target of targets) {
      const current = existsSync(target.filePath) ? readText(target.filePath) : null;
      if (current !== target.content) stale.push(target);
    }
    if (stale.length === 0) {
      console.log(`generate-agent-shims --check: all ${targets.length} shim(s) up to date.`);
      process.exit(0);
    }
    process.stderr.write(`generate-agent-shims --check: ${stale.length} stale shim(s):\n\n`);
    for (const target of stale) {
      const label = relFromRoot(target.filePath);
      process.stderr.write(`--- ${label} ---\n`);
      const current = existsSync(target.filePath) ? readText(target.filePath) : '(file does not exist)';
      process.stderr.write(`-- expected (from .sdd/runtimes.yml) --\n${target.content}\n`);
      process.stderr.write(`-- actual (on disk) --\n${current}\n\n`);
    }
    process.stderr.write('Run `node scripts/generate-agent-shims.mjs` to regenerate, or `npm run generate:agent-shims`.\n');
    process.exit(1);
  }

  mkdirSync(claudeAgentsDir, { recursive: true });
  let skippedDirty = 0;
  let written = 0;
  for (const target of targets) {
    const current = existsSync(target.filePath) ? readText(target.filePath) : null;
    if (current === target.content) continue; // already up to date

    if (current !== null && !forceMode && isGitDirty(target.filePath)) {
      process.stderr.write(
        `generate-agent-shims: WARNING — ${relFromRoot(target.filePath)} has uncommitted changes and would be ` +
        `overwritten by regeneration. Skipping it. Commit or stash your changes (or discard them) and rerun, ` +
        `or pass --force if you intended to overwrite it (e.g. mid-iteration on runtimes.yml, before committing ` +
        `the previous regeneration).\n`
      );
      skippedDirty += 1;
      continue;
    }

    writeFileSync(target.filePath, target.content, { encoding: 'utf8' });
    written += 1;
    console.log(`generate-agent-shims: wrote ${relFromRoot(target.filePath)}`);
  }

  console.log(`generate-agent-shims: ${written} written, ${skippedDirty} skipped (uncommitted changes), ${targets.length - written - skippedDirty} already up to date.`);
  if (skippedDirty > 0) process.exit(1);
}

main();
