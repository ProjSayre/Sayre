import { FEATURES, NODE_BY_ID, TICKET_BY_ID, sharedMembers } from "../data";
import type { Feature } from "../data";
import { Chip } from "../shared/Chip";
import { ChangeRow } from "./Sidebar";
import { useDemoDispatch } from "./state";

/** §8.4 feature panel — PRD §4.7's four fields + stats */
export function FeaturePanel({ feature }: { feature: Feature }): JSX.Element {
  const dispatch = useDemoDispatch();

  const sharedLines = FEATURES.filter((f) => f.id !== feature.id)
    .map((other) => ({ other, files: sharedMembers(feature, other) }))
    .filter((s) => s.files.length > 0);

  return (
    <div className="featurepanel">
      <div className="featurepanel__name">{feature.name}</div>
      <div className="featurepanel__team">team: {feature.team}</div>

      <section className="section">
        <div className="section-heading">progress</div>
        <div className="featurepanel__progress">
          {feature.stats.openTickets} open tickets · {feature.stats.mergedPrs} merged prs · shipped {feature.stats.lastShip}
        </div>
      </section>

      <section className="section">
        <div className="section-heading">description</div>
        <p className="section-desc">{feature.description}</p>
        <div className="section-credit">generated by sayre · sample</div>
      </section>

      <section className="section">
        <div className="section-heading">files included</div>
        {feature.memberIds.map((id) => (
          <button key={id} className="featurepanel__file" onClick={() => dispatch({ type: "selectFileForTab", id })}>
            {id}
          </button>
        ))}
        {sharedLines.map(({ other, files }) => (
          <div key={other.id} className="featurepanel__shared">
            shares {files.map((f) => NODE_BY_ID.get(f)?.name ?? f).join(", ")} with {other.name}
          </div>
        ))}
      </section>

      <section className="section">
        <div className="section-heading">recent edits</div>
        {feature.recentEdits.map((c) => (
          <ChangeRow key={c.sha} change={c} />
        ))}
      </section>

      <section className="section">
        <div className="section-heading">tickets</div>
        {feature.ticketIds.map((tid) => {
          const t = TICKET_BY_ID.get(tid);
          if (!t) return null;
          return (
            <div key={tid} className={t.status === "done" ? "ticket ticket--done" : "ticket"}>
              <Chip>{t.id}</Chip>
              <span className="ticket__title">{t.title}</span>
              <span className="ticket__status">{t.status}</span>
            </div>
          );
        })}
      </section>
    </div>
  );
}
